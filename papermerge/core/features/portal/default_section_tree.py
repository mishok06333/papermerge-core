async def _get_or_create_portal_folder(
    db_session: AsyncSession,
    *,
    parent_id: UUID,
    group_id: UUID,
    title: str,
) -> UUID:
    stmt = select(orm.Folder.id).where(
        orm.Folder.parent_id == parent_id,
        orm.Folder.group_id == group_id,
        orm.Folder.title == title,
        orm.Folder.ctype == core_constants.CTYPE_FOLDER,
        orm.Folder.deleted_at.is_(None),
    )
    existing = await db_session.scalar(stmt)
    if existing is not None:
        return existing

    folder_id = uuid.uuid4()
    folder = orm.Folder(
        id=folder_id,
        title=title,
        ctype=core_constants.CTYPE_FOLDER,
        group_id=group_id,
        user_id=None,
        parent_id=parent_id,
        lang="xxx",
    )
    db_session.add(folder)
    await db_session.flush()
    return folder_id


async def _ensure_subtree(
    db_session: AsyncSession,
    *,
    parent_id: UUID,
    group_id: UUID,
    nodes: list[SectionSpec],
) -> None:
    for title, children in nodes:
        folder_id = await _get_or_create_portal_folder(
            db_session,
            parent_id=parent_id,
            group_id=group_id,
            title=title,
        )
        if children:
            await _ensure_subtree(
                db_session,
                parent_id=folder_id,
                group_id=group_id,
                nodes=children,
            )


async def ensure_portal_default_section_tree(
    db_session: AsyncSession,
    root_node_id: UUID,
    group_id: UUID,
) -> None:
    """Create default section folders under the portal root (idempotent)."""
    await _ensure_subtree(
        db_session,
        parent_id=root_node_id,
        group_id=group_id,
        nodes=PORTAL_DEFAULT_SECTION_TREE,
    )
    logger.info(
        "Portal default section tree ensured under root_node_id=%s", root_node_id
    )
